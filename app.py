def safe_extract(zip_path: Path, dest: Path) -> None:
    dest = dest.resolve()
    with zipfile.ZipFile(zip_path) as zf:
        for member in zf.infolist():
            entry = Path(member.filename)
            if entry.is_absolute() or member.filename.startswith(("/", "\\")):
                raise HTTPException(400, "Unsafe ZIP entry detected.")
            if member.external_attr >> 16 & 0o170000 == 0o120000:
                raise HTTPException(400, "Unsafe ZIP symlink detected.")
            target = (dest / entry).resolve()
            try:
                target.relative_to(dest)
            except ValueError:
                raise HTTPException(400, "Unsafe ZIP entry detected.")
        zf.extractall(dest)


def cobol_to_python(source: str, name: str) -> str:
    """Heuristic starter converter. Replace with a parser/LLM-powered engine for production."""
    program = Path(name).stem.lower().replace("-", "_").replace(" ", "_")
    lines = ['"""Generated from legacy COBOL source.', 'This starter conversion preserves intent and markers; review before production use.', '"""', "", "from __future__ import annotations", "", "def main() -> None:"]
    working = []
    paragraphs = []
    for raw in source.splitlines():
        s = raw.strip()
        if not s:
            continue
        if re.match(r"^[A-Z0-9-]+\.$", s):
            paragraphs.append(s[:-1].lower().replace("-", "_"))
        m = re.match(r"^01\s+([A-Z0-9-]+)", s)
        if m:
            working.append(m.group(1).lower().replace("-", "_"))
    lines.append(f"    # Source program: {Path(name).name}")
    lines.append(f"    # Converted program: {program}")
    for field in working[:25]:
        lines.append(f"    {field} = None  # COBOL data item")
    if paragraphs:
        for p in paragraphs[:40]:
            lines.append(f"    # TODO: implement paragraph {p} from COBOL")
    lines.append("    print('COBOL conversion scaffold generated successfully')")
    lines += ["", "", "if __name__ == '__main__':", "    main()"]
    return "\n".join(lines) + "\n"


def extract_sql(source: str) -> str:
    statements: List[str] = []
    for m in re.finditer(r"EXEC\s+SQL(.*?)END-EXEC", source, re.I | re.S):
        body = re.sub(r"\s+", " ", m.group(1)).strip()
        if body:
            statements.append(body)
    tables = sorted(set(re.findall(r"\b(?:FROM|JOIN|INTO|UPDATE|TABLE)\s+([A-Z0-9_.$-]+)", source, re.I)))
    ddl = []
    if tables:
        ddl.append("-- Tables referenced by COBOL SQL blocks")
        for table in tables:
            ddl.append(f"-- {table}")
    if statements:
        ddl.append("\n-- Extracted SQL statements")
        for stmt in statements:
            ddl.append(stmt.rstrip(";") + ";")
    else:
        ddl.append("-- No EXEC SQL blocks detected in this source file.")
    return "\n".join(ddl) + "\n"


def discover_cobol(root: Path) -> List[Path]:
    exts = {".cbl", ".cob", ".cobol", ".cpy", ".CBL", ".COB", ".CPY"}
    return [p for p in root.rglob("*") if p.is_file() and p.suffix in exts]


def build_output(source_root: Path, output_dir: Path) -> List[Dict[str, str]]:
    files = discover_cobol(source_root)
    if not files:
        files = [p for p in source_root.rglob("*") if p.is_file() and p.suffix.lower() in {".txt", ".src"}]
    results: List[Dict[str, str]] = []
    for src in files:
        rel = src.relative_to(source_root)
        try:
            text = src.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        py_rel = rel.with_suffix(".py")
        sql_rel = Path("sql") / (rel.stem + ".sql")
        py_path = output_dir / py_rel
        sql_path = output_dir / sql_rel
        py_path.parent.mkdir(parents=True, exist_ok=True)
        sql_path.parent.mkdir(parents=True, exist_ok=True)
        py_path.write_text(cobol_to_python(text, str(rel)), encoding="utf-8")
        sql_path.write_text(extract_sql(text), encoding="utf-8")
        results.append({"source": str(rel), "python": str(py_rel), "sql": str(sql_rel)})
    (output_dir / "README.md").write_text("# Legacy to Modernization output\n\nGenerated by the starter COBOL modernization pipeline.\n\nImportant: generated code is a reviewable scaffold. Production migration should include parser-level validation, business-rule mapping, data-model reconciliation, test generation, and human approval.\n", encoding="utf-8")
    return results


def zip_dir(src_dir: Path, zip_path: Path) -> None:
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in src_dir.rglob("*"):
            if path.is_file():
                zf.write(path, path.relative_to(src_dir))


