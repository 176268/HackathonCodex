@app.post("/api/convert")
async def convert(source_type: str = Form(...), git_url: str | None = Form(default=None), cobol_zip: UploadFile | None = File(default=None)):
    job_id = next(tempfile._get_candidate_names())
    root = WORK / job_id
    output = OUTPUT / job_id
    root.mkdir(parents=True, exist_ok=True)
    output.mkdir(parents=True, exist_ok=True)
    try:
        if source_type == "zip":
            if not cobol_zip or not cobol_zip.filename:
                raise HTTPException(400, "Please upload a COBOL ZIP file.")
            if not cobol_zip.filename.lower().endswith(".zip"):
                raise HTTPException(400, "Only ZIP archives are accepted.")
            incoming = root / "project.zip"
            with incoming.open("wb") as f:
                shutil.copyfileobj(cobol_zip.file, f)
            safe_extract(incoming, root / "src")
            source_root = root / "src"
        elif source_type == "git":
            if not git_url or not re.match(r"^https?://", git_url):
                raise HTTPException(400, "Please provide a valid HTTPS Git URL.")
            source_root = root / "src"
            proc = subprocess.run(["git", "clone", "--depth", "1", git_url, str(source_root)], capture_output=True, text=True, timeout=120)
            if proc.returncode != 0:
                raise HTTPException(400, f"Git clone failed: {proc.stderr[-1200:]}")
        else:
            raise HTTPException(400, "Unsupported source type.")
        results = build_output(source_root, output)
        archive = OUTPUT / f"legacy-to-modernization-{job_id}.zip"
        zip_dir(output, archive)
        return JSONResponse({"job_id": job_id, "message": "Conversion completed.", "files": results, "download_url": f"/api/download/{job_id}", "preview_root": str(output)})
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(500, f"Conversion failed: {exc}")


@app.get("/api/preview/{job_id}")
def preview(job_id: str):
    output = OUTPUT / job_id
    if not output.exists():
        raise HTTPException(404, "Job not found.")
    files = []
    for p in output.rglob("*"):
        if p.is_file():
            rel = str(p.relative_to(output))
            text = p.read_text(encoding="utf-8", errors="ignore")
            files.append({"path": rel, "content": text[:50000]})
    return {"files": sorted(files, key=lambda x: x["path"])}


@app.get("/api/download/{job_id}")
def download(job_id: str):
    archive = OUTPUT / f"legacy-to-modernization-{job_id}.zip"
    if not archive.exists():
        raise HTTPException(404, "Download not found.")
    return FileResponse(archive, filename=archive.name, media_type="application/zip")
